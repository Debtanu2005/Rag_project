from prometheus_client import Counter, Histogram, start_http_server

REQUESTS = Counter(
    "rag_requests_total",
    "RAG pipeline requests",
    ["status"],  # answered | rejected | error
)

REQUEST_LATENCY = Histogram(
    "rag_request_latency_seconds",
    "End-to-end latency of a RAG pipeline request",
    buckets=(0.5, 1, 2, 3, 5, 7.5, 10, 15, 20, 30, 60),
)

TTFT = Histogram(
    "rag_ttft_seconds",
    "Time from receiving the query to the first answer token",
    buckets=(0.25, 0.5, 1, 1.5, 2, 3, 5, 7.5, 10, 15, 30),
)

TOKENS_PER_SECOND = Histogram(
    "rag_tokens_per_second",
    "Answer generation throughput after the first token",
    buckets=(5, 10, 20, 30, 50, 75, 100, 150, 200, 300, 500),
)

OUTPUT_TOKENS = Counter(
    "rag_output_tokens_total",
    "Answer tokens generated by the LLM",
)

NODE_LATENCY = Histogram(
    "rag_node_latency_seconds",
    "Latency of each LangGraph node",
    ["node"],
    buckets=(0.05, 0.1, 0.25, 0.5, 1, 2, 3, 5, 10, 20),
)


def start_metrics_server(port: int = 8000):
    start_http_server(port)
    print(f"Prometheus metrics available at http://localhost:{port}/metrics")
